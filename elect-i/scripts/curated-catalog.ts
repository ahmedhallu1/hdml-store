/**
 * Curated (non-mirrored) catalog data for `scripts/seed-catalog.ts`.
 *
 * The HDML mirror is an electronics catalog, so on its own it would leave seven
 * of the eight top-level groups empty and the category pages, filters and
 * supplier listings unexercised. These templates fill them.
 *
 * Everything here is DATA ONLY and deliberately deterministic: a template
 * expands to one product per variant, its price is `baseCents + stepCents * i`,
 * and its SKU is hashed from (category slug, template name, variant). Re-running
 * the seed therefore produces byte-identical rows — no randomness anywhere.
 *
 * Prices are integer USD cents. Nothing in this file does float math.
 */

import type { StockStatus, VerificationLevel } from "../src/lib/db-types";

/** The seven groups the HDML mirror does not cover. */
export type CuratedGroupKey =
  | "industrial"
  | "home"
  | "fashion"
  | "office"
  | "automotive"
  | "other"
  | "medical";

export interface CuratedTemplate {
  /** One of the eight `eig.categories.group_key` values. */
  group: CuratedGroupKey;
  name: string;
  unit: string;
  moq: number;
  /** List price of the FIRST variant, in USD cents. */
  baseCents: number;
  /** Added once per variant index, in USD cents. */
  stepCents: number;
  leadTimeDays: number;
  stock: StockStatus;
  /** Written to `products.specs` (jsonb) verbatim. */
  specs: Record<string, string>;
  variants: string[];
  /** How many quantity break tiers this template gets (2–4). */
  tiers: 2 | 3 | 4;
}


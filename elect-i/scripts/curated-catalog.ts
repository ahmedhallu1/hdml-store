export interface SeedSupplier {
  slug: string;
  name: string;
  country: string;
  city: string;
  /**
   * Reflects the documents the supplier has SUBMITTED — nothing more.
   * `audited` is deliberately never used: the platform states plainly that it
   * does not run independent factory audits, and a seeded row must not
   * contradict that.
   */
  verification: VerificationLevel;
  responseRate: number;
  leadTimeDays: number;
  description: string;
}

